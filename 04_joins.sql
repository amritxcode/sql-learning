-- Q11. Show customer name, restaurant name
-- and order amount for every order.

SELECT
    customers.name,
    restaurants.restaurant_name,
    orders.amount
FROM orders
INNER JOIN customers
ON orders.customer_id = customers.customer_id
INNER JOIN restaurants
ON orders.restaurant_id = restaurants.restaurant_id;


-- Q12. Find total revenue generated by each restaurant.

SELECT
    restaurants.restaurant_name,
    restaurants.city,
    SUM(orders.amount) AS total_revenue
FROM orders
INNER JOIN restaurants
ON orders.restaurant_id = restaurants.restaurant_id
GROUP BY restaurants.restaurant_id,
         restaurants.restaurant_name,
         restaurants.city
ORDER BY total_revenue DESC;